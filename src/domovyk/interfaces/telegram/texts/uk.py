def meter_kinds_label(kinds: list[str]) -> str:
    """['gas', 'water_cold'] → «газу й холодної води»."""
    names = [METER_KINDS_GENITIVE.get(k, k) for k in dict.fromkeys(kinds)]
    if len(names) <= 1:
        return "".join(names)
    return ", ".join(names[:-1]) + " й " + names[-1]
